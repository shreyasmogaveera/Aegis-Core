const Alert = require('../models/Alert');
const socketService = require('../services/socketService');


class AlertController {
  /**
   * Utility helper to format time relative string
   */
  formatTimeAgo(date) {
    if (!date) return 'Just now';
    const seconds = Math.floor((new Date() - new Date(date)) / 1000);
    if (seconds < 60) return `${Math.max(1, seconds)}s ago`;
    const minutes = Math.floor(seconds / 60);
    if (minutes < 60) return `${minutes}m ago`;
    const hours = Math.floor(minutes / 60);
    if (hours < 24) return `${hours}h ago`;
    const days = Math.floor(hours / 24);
    return `${days}d ago`;
  }

  /**
   * Format Alert document for response and socket emission
   */
  formatAlert(alert) {
    const updatedAt = alert.updatedAt || alert.createdAt;
    const pop = alert.affectedPopulation || 0;
    const zone = alert.affectedZone || 'Mapped hazard corridor';
    const basis = alert.populationBasis || 'Estimated figure, not verified against official DDMP records';

    return {
      id: alert._id.toString(),
      type: `${alert.riskLevel} ${(alert.hazardType || 'GENERAL').replace('_', ' ')}`,
      title: alert.title,
      desc: alert.description,
      description: alert.description,
      hazardType: alert.hazardType,
      riskLevel: alert.riskLevel,
      severity: alert.riskLevel ? alert.riskLevel.toLowerCase() : 'high',
      district: alert.district,
      location: alert.location,
      affectedZone: zone,
      affectedPopulation: pop,
      populationBasis: basis,
      affected: pop > 0 ? `${zone} (~${pop.toLocaleString()} est. pop. — ${basis})` : zone,
      source: alert.source || 'AegisCore Prediction Engine',
      status: alert.status,
      time: this.formatTimeAgo(updatedAt),
      activeSince: this.formatTimeAgo(alert.createdAt),
      lastEvaluated: this.formatTimeAgo(updatedAt),
      createdAt: alert.createdAt,
      updatedAt: alert.updatedAt,
      expiresAt: alert.expiresAt,
      isAutoGenerated: alert.isAutoGenerated || false,
      technicalDetails: alert.technicalDetails || null
    };
  }

  /**
   * Helper filter for non-expired active alerts (expiresAt in future or within 24h fallback window)
   */
  getActiveAlertFilter(additionalQuery = {}) {
    const now = new Date();
    const cutoff24h = new Date(now.getTime() - 24 * 60 * 60 * 1000);
    return {
      status: 'ACTIVE',
      source: { $ne: 'test' },
      title: { $not: /^E2E /i },
      $or: [
        { expiresAt: { $gt: now } },
        { expiresAt: { $exists: false }, createdAt: { $gte: cutoff24h } }
      ],
      ...additionalQuery
    };
  }

  /**
   * Get active alerts for authenticated users (Citizen & Admin)
   */
  async getActiveAlerts(req, res) {
    try {
      const { district, riskLevel } = req.query;
      const additionalQuery = {};

      if (district) {
        additionalQuery.district = new RegExp(district, 'i');
      }
      if (riskLevel) {
        additionalQuery.riskLevel = riskLevel.toUpperCase();
      }

      const query = this.getActiveAlertFilter(additionalQuery);

      const alerts = await Alert.find(query).sort({ createdAt: -1 });

      const formattedAlerts = alerts.map((alert) => this.formatAlert(alert));

      return res.status(200).json({
        count: formattedAlerts.length,
        alerts: formattedAlerts
      });
    } catch (err) {
      console.error('[AlertController.getActiveAlerts] Error:', err);
      return res.status(500).json({ error: 'Failed to retrieve active alerts' });
    }
  }

  /**
   * Get single alert details by ID
   */
  async getAlertById(req, res) {
    try {
      const alert = await Alert.findById(req.params.id);
      if (!alert) {
        return res.status(404).json({ error: 'Alert not found' });
      }

      return res.status(200).json(this.formatAlert(alert));
    } catch (err) {
      console.error('[AlertController.getAlertById] Error:', err);
      return res.status(500).json({ error: 'Failed to retrieve alert details' });
    }
  }

  /**
   * Admin: Get all alerts with summary statistics.
   * By default returns ACTIVE alerts matching summary counters.
   * Query param ?status=ALL or ?status=RESOLVED supported.
   */
  async getAdminAlerts(req, res) {
    try {
      const { status = 'ACTIVE' } = req.query;
      const notTestQuery = {
        source: { $ne: 'test' },
        title: { $not: /^E2E /i }
      };

      const activeFilter = this.getActiveAlertFilter(notTestQuery);
      const totalActive = await Alert.countDocuments(activeFilter);
      const criticalCount = await Alert.countDocuments({ ...activeFilter, riskLevel: 'CRITICAL' });
      const highCount = await Alert.countDocuments({ ...activeFilter, riskLevel: 'HIGH' });
      const moderateCount = await Alert.countDocuments({ ...activeFilter, riskLevel: 'MODERATE' });
      const lowCount = await Alert.countDocuments({ ...activeFilter, riskLevel: 'LOW' });
      const resolvedCount = await Alert.countDocuments({ ...notTestQuery, status: 'RESOLVED' });

      let listQuery;
      if (status.toUpperCase() === 'ALL') {
        listQuery = notTestQuery;
      } else if (status.toUpperCase() === 'RESOLVED') {
        listQuery = { ...notTestQuery, status: 'RESOLVED' };
      } else {
        // Default to ACTIVE: strictly match activeFilter so the visible list exactly matches totalActive!
        listQuery = activeFilter;
      }

      const alerts = await Alert.find(listQuery).sort({ createdAt: -1 });
      const formattedAlerts = alerts.map((alert) => this.formatAlert(alert));

      return res.status(200).json({
        summary: {
          totalActive,
          critical: criticalCount,
          high: highCount,
          moderate: moderateCount,
          low: lowCount,
          totalResolved: resolvedCount
        },
        alerts: formattedAlerts
      });
    } catch (err) {
      console.error('[AlertController.getAdminAlerts] Error:', err);
      return res.status(500).json({ error: 'Failed to retrieve admin alerts' });
    }
  }

  /**
   * Admin: Create new alert
   */
  async createAlert(req, res) {
    try {
      const {
        title,
        description,
        hazardType,
        riskLevel,
        district,
        location,
        affectedPopulation,
        source
      } = req.body;

      if (!title || !description || !riskLevel || !district) {
        return res.status(400).json({
          error: 'Title, description, risk level, and district are required'
        });
      }

      const validRiskLevels = ['LOW', 'MODERATE', 'HIGH', 'CRITICAL'];
      if (!validRiskLevels.includes(riskLevel.toUpperCase())) {
        return res.status(400).json({ error: 'Invalid risk level. Allowed: LOW, MODERATE, HIGH, CRITICAL' });
      }

      const newAlert = await Alert.create({
        title,
        description,
        hazardType: hazardType || 'GENERAL',
        riskLevel: riskLevel.toUpperCase(),
        district,
        location: location || { type: 'Point', coordinates: [0, 0] },
        affectedPopulation: affectedPopulation || 0,
        source: source || 'AegisCore Command Center',
        status: 'ACTIVE',
        issuedBy: req.user.userId
      });

      const formattedAlert = this.formatAlert(newAlert);
      socketService.notifyAlertCreated(formattedAlert);

      return res.status(201).json({
        message: 'Alert created successfully',
        alert: formattedAlert
      });
    } catch (err) {
      console.error('[AlertController.createAlert] Error:', err);
      return res.status(500).json({ error: 'Failed to create alert' });
    }
  }

  /**
   * Admin: Update alert details
   */
  async updateAlert(req, res) {
    try {
      const { id } = req.params;
      const updateData = req.body;

      if (updateData.riskLevel) {
        updateData.riskLevel = updateData.riskLevel.toUpperCase();
      }

      const updatedAlert = await Alert.findByIdAndUpdate(id, updateData, { new: true, runValidators: true });
      if (!updatedAlert) {
        return res.status(404).json({ error: 'Alert not found' });
      }

      const formattedAlert = this.formatAlert(updatedAlert);
      socketService.notifyAlertUpdated(formattedAlert);

      return res.status(200).json({
        message: 'Alert updated successfully',
        alert: formattedAlert
      });
    } catch (err) {
      console.error('[AlertController.updateAlert] Error:', err);
      return res.status(500).json({ error: 'Failed to update alert' });
    }
  }

  /**
   * Admin: Deactivate / Resolve alert
   */
  async deactivateAlert(req, res) {
    try {
      const { id } = req.params;
      const { status } = req.body;

      const targetStatus = status || 'RESOLVED';
      if (!['RESOLVED', 'CANCELLED', 'ACTIVE'].includes(targetStatus)) {
        return res.status(400).json({ error: 'Invalid status. Allowed: ACTIVE, RESOLVED, CANCELLED' });
      }

      const updatedAlert = await Alert.findByIdAndUpdate(
        id,
        { status: targetStatus },
        { new: true }
      );

      if (!updatedAlert) {
        return res.status(404).json({ error: 'Alert not found' });
      }

      const formattedAlert = this.formatAlert(updatedAlert);
      socketService.notifyAlertUpdated(formattedAlert);

      return res.status(200).json({
        message: `Alert status updated to ${targetStatus}`,
        alert: formattedAlert
      });
    } catch (err) {
      console.error('[AlertController.deactivateAlert] Error:', err);
      return res.status(500).json({ error: 'Failed to update alert status' });
    }
  }

  /**
   * Admin: Delete alert (for test cleanup or permanent purge)
   */
  async deleteAlert(req, res) {
    try {
      const { id } = req.params;
      const alert = await Alert.findByIdAndDelete(id);
      if (!alert) {
        return res.status(404).json({ error: 'Alert not found' });
      }
      return res.status(200).json({ message: 'Alert deleted successfully' });
    } catch (err) {
      console.error('[AlertController.deleteAlert] Error:', err);
      return res.status(500).json({ error: 'Failed to delete alert' });
    }
  }
}

module.exports = new AlertController();
