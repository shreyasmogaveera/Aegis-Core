const {
  User,
  Alert,
  SosRequest,
  Shelter,
  Prediction,
  EnvironmentalData
} = require('../models');

class DashboardService {
  /**
   * Helper function to format relative timestamps (e.g. "10m ago", "2h ago")
   */
  formatTimeAgo(date) {
    if (!date) return 'Just now';
    const seconds = Math.floor((new Date() - new Date(date)) / 1000);
    if (seconds < 60) return `${Math.max(1, seconds)}s ago`;
    const minutes = Math.floor(seconds / 60);
    if (minutes < 60) return `${minutes}m ago`;
    const hours = Math.floor(minutes / 60);
    if (hours < 24) return `${hours}h ago`;
    const days = Math.floor(hours / 24);
    return `${days}d ago`;
  }

  /**
   * Helper filter for non-expired active alerts (expiresAt in future or within 24h fallback window)
   */
  getActiveAlertFilter(additionalQuery = {}) {
    const now = new Date();
    const cutoff24h = new Date(now.getTime() - 24 * 60 * 60 * 1000);
    return {
      status: 'ACTIVE',
      $or: [
        { expiresAt: { $gt: now } },
        { expiresAt: { $exists: false }, createdAt: { $gte: cutoff24h } }
      ],
      ...additionalQuery
    };
  }

  /**
   * Aggregate & return Admin Dashboard Summary from MongoDB
   */
  async getAdminDashboardSummary() {
    try {
      // 1. Active SOS Count (PENDING or IN_PROGRESS)
      const activeSosCount = await SosRequest.countDocuments({
        status: { $in: ['PENDING', 'IN_PROGRESS'] }
      });

      const pendingSosCount = await SosRequest.countDocuments({ status: 'PENDING' });
      const respondingSosCount = await SosRequest.countDocuments({ status: 'IN_PROGRESS' });

      // 2. Critical Zones Count (Active non-expired alerts with CRITICAL or HIGH risk)
      const criticalZonesCount = await Alert.countDocuments(
        this.getActiveAlertFilter({ riskLevel: { $in: ['CRITICAL', 'HIGH'] } })
      );

      // 3. Environmental Summary (regional overall averages across supported districts)
      const allEnv = await EnvironmentalData.find({
        district: { $in: ['Kodagu', 'Uttara Kannada', 'Belagavi', 'Bagalkot'] }
      }).sort({ recordedAt: -1 }).limit(4);

      let avgRainfall = 110.15;
      let avgRiverLevel = 4.75;
      let avgSoilMoisture = 85.5;

      if (allEnv && allEnv.length > 0) {
        avgRainfall = Number((allEnv.reduce((acc, e) => acc + (e.rainfall || 0), 0) / allEnv.length).toFixed(1));
        avgRiverLevel = Number((allEnv.reduce((acc, e) => acc + (e.riverLevel || 0), 0) / allEnv.length).toFixed(1));
        avgSoilMoisture = Number((allEnv.reduce((acc, e) => acc + (e.soilMoisture || 0), 0) / allEnv.length).toFixed(1));
      }

      const environmentalSummary = {
        rainfall_mm: avgRainfall,
        river_level_m: avgRiverLevel,
        soil_moisture_pct: avgSoilMoisture,
        district: 'KARNATAKA OVERVIEW'
      };

      // 4. Intelligence Feed / Active Non-Expired Alerts from MongoDB
      const alerts = await Alert.find(this.getActiveAlertFilter())
        .sort({ createdAt: -1 })
        .limit(10);

      const intelligenceFeed = alerts.map((alert) => {
        const updatedAt = alert.updatedAt || alert.createdAt;
        return {
          id: alert._id.toString(),
          district: alert.district,
          title: alert.title,
          description: alert.description,
          riskLevel: alert.riskLevel,
          hazardType: alert.hazardType,
          time: this.formatTimeAgo(updatedAt),
          timeAgo: this.formatTimeAgo(alert.createdAt),
          activeSince: this.formatTimeAgo(alert.createdAt),
          lastEvaluated: this.formatTimeAgo(updatedAt),
          createdAt: alert.createdAt,
          updatedAt: alert.updatedAt,
          expiresAt: alert.expiresAt,
          isAutoGenerated: alert.isAutoGenerated || false,
          technicalDetails: alert.technicalDetails || null
        };
      });

      // 5. Critical Zones List
      const predictions = await Prediction.find({ riskLevel: { $in: ['CRITICAL', 'HIGH'] } })
        .sort({ riskScore: -1 })
        .limit(5);

      const criticalZones = predictions.map((pred) => ({
        id: pred._id.toString(),
        district: pred.district,
        riskLevel: pred.riskLevel,
        riskScore: pred.riskScore,
        timeAgo: this.formatTimeAgo(pred.updatedAt || pred.createdAt)
      }));

      return {
        activeSosCount,
        criticalZonesCount: typeof criticalZonesCount === 'number' ? criticalZonesCount : 0,
        environmentalSummary,
        intelligenceFeed,
        criticalZones,
        sosBreakdown: {
          pending: pendingSosCount,
          responding: respondingSosCount
        }
      };
    } catch (err) {
      console.error('[DashboardService.getAdminDashboardSummary] Error:', err);
      throw err;
    }
  }

  /**
   * Aggregate & return User/Citizen Dashboard Summary from MongoDB
   */
  /**
   * Aggregate & return User/Citizen Dashboard Summary from MongoDB
   */
  async getUserDashboardSummary(userId, requestedDistrict, userCoords = {}) {
    try {
      const { resolveDominantPrediction } = require('../utils/dominantHazard');
      const calibrationService = require('./calibrationService');
      const supportedDistricts = ['Kodagu', 'Uttara Kannada', 'Belagavi', 'Bagalkot'];

      // Determine user district: requested district, profile agency, or Kodagu default
      let userDistrict = 'Kodagu';
      if (requestedDistrict && supportedDistricts.some(d => d.toLowerCase() === requestedDistrict.toLowerCase())) {
        userDistrict = supportedDistricts.find(d => d.toLowerCase() === requestedDistrict.toLowerCase());
      } else if (userId) {
        const dbUser = await User.findById(userId);
        if (dbUser && dbUser.agency && supportedDistricts.some(d => d.toLowerCase() === dbUser.agency.toLowerCase())) {
          userDistrict = supportedDistricts.find(d => d.toLowerCase() === dbUser.agency.toLowerCase());
        }
      }

      // 1. Fetch latest flood and landslide predictions for user's district with case-insensitive regex
      const candidateHazards = ['FLOOD', 'LANDSLIDE'];
      const rawHazards = await Promise.all(
        candidateHazards.map((h) =>
          Prediction.findOne({
            district: new RegExp(`^${userDistrict}$`, 'i'),
            predictionType: new RegExp(`^${h}$`, 'i')
          }).sort({ createdAt: -1 })
        )
      );

      // Calibrate each candidate hazard
      const formattedHazards = rawHazards.filter(Boolean).map((p) => {
        const hazard = (p.predictionType || 'flood').toLowerCase();
        const score = p.riskScore !== undefined ? p.riskScore : (p.rawProbability ?? 0);
        const calib = calibrationService.classifyRisk(
          hazard,
          p.district,
          score,
          p.calibratedProbability
        );
        return {
          ...p.toObject(),
          riskLevel: calib.riskLevel || p.riskLevel || 'LOW',
          calibratedProbability: p.calibratedProbability !== undefined && p.calibratedProbability !== null
            ? p.calibratedProbability
            : (p.rawProbability ?? score),
          operationalDecision: calib.operationalDecision || p.operationalDecision,
          predictionType: (p.predictionType || 'FLOOD').toUpperCase()
        };
      });

      // Canonical Dominant Hazard Resolution (CRITICAL > HIGH > MODERATE > LOW, probability tiebreak)
      const dominantPred = resolveDominantPrediction(formattedHazards);

      const riskLevel = dominantPred?.riskLevel || 'LOW';
      const calibProb = dominantPred?.calibratedProbability !== undefined && dominantPred?.calibratedProbability !== null
        ? dominantPred.calibratedProbability
        : 0.03;
      const dominantHazardType = dominantPred?.predictionType || 'FLOOD';

      // Citizen Safety Index: 0-100 scale directly inversely proportional to calibrated probability
      const safetyScore = Math.max(10, Math.min(99, Math.round((1 - calibProb) * 100)));

      // 2. Fetch top active alert for user's district
      const topAlert = await Alert.findOne(this.getActiveAlertFilter({ district: userDistrict }))
        .sort({ createdAt: -1 })
        || await Alert.findOne(this.getActiveAlertFilter()).sort({ createdAt: -1 });

      let alertTitle = topAlert ? topAlert.title : null;
      if (!alertTitle) {
        if (riskLevel === 'CRITICAL') alertTitle = `Critical ${dominantHazardType === 'LANDSLIDE' ? 'Landslide' : 'Flood'} Warning — ${userDistrict}`;
        else if (riskLevel === 'HIGH') alertTitle = `High ${dominantHazardType === 'LANDSLIDE' ? 'Landslide' : 'Flood'} Advisory — ${userDistrict}`;
        else if (riskLevel === 'MODERATE') alertTitle = `Heightened ${dominantHazardType === 'LANDSLIDE' ? 'Landslide' : 'Flood'} Advisory — ${userDistrict}`;
        else alertTitle = `Normal Conditions Monitored — ${userDistrict}`;
      }

      // 3. Count active advisories & genuinely active high/critical risks across the 4 districts
      const activeAdvisoriesCount = await Alert.countDocuments(this.getActiveAlertFilter());

      // Evaluate active elevated hazards across all 4 districts
      let nearbyRisksCount = 0;
      for (const d of supportedDistricts) {
        const districtPreds = await Promise.all(
          candidateHazards.map((h) =>
            Prediction.findOne({
              district: new RegExp(`^${d}$`, 'i'),
              predictionType: new RegExp(`^${h}$`, 'i')
            }).sort({ createdAt: -1 })
          )
        );
        const dFormatted = districtPreds.filter(Boolean).map((p) => {
          const hz = (p.predictionType || 'flood').toLowerCase();
          const sc = p.riskScore !== undefined ? p.riskScore : (p.rawProbability ?? 0);
          const c = calibrationService.classifyRisk(hz, p.district, sc, p.calibratedProbability);
          return {
            ...p.toObject(),
            riskLevel: c.riskLevel || p.riskLevel || 'LOW',
            calibratedProbability: p.calibratedProbability ?? sc
          };
        });
        const dom = resolveDominantPrediction(dFormatted);
        if (dom && (dom.riskLevel === 'HIGH' || dom.riskLevel === 'CRITICAL')) {
          nearbyRisksCount++;
        }
      }

      // 4. Fetch nearest open shelter in user's district
      const nearestShelterDoc = await Shelter.findOne({ status: 'OPEN', district: userDistrict })
        || await Shelter.findOne({ status: 'OPEN' });

      let shelterDistanceStr = `${userDistrict} Sector`;
      if (nearestShelterDoc && userCoords?.lat && userCoords?.lng && nearestShelterDoc.location?.coordinates) {
        const [shLng, shLat] = nearestShelterDoc.location.coordinates;
        const R = 6371;
        const dLat = ((shLat - userCoords.lat) * Math.PI) / 180;
        const dLon = ((shLng - userCoords.lng) * Math.PI) / 180;
        const a =
          Math.sin(dLat / 2) * Math.sin(dLat / 2) +
          Math.cos((userCoords.lat * Math.PI) / 180) *
            Math.cos((shLat * Math.PI) / 180) *
            Math.sin(dLon / 2) *
            Math.sin(dLon / 2);
        const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
        const distKm = R * c;
        if (distKm > 35) {
          shelterDistanceStr = `~${Math.round(distKm)} km away (${nearestShelterDoc.district})`;
        } else {
          shelterDistanceStr = `${distKm < 1 ? '< 1 km' : distKm.toFixed(1) + ' km'} away (${nearestShelterDoc.district})`;
        }
      }

      const nearestShelter = nearestShelterDoc ? {
        id: nearestShelterDoc._id.toString(),
        name: nearestShelterDoc.name,
        address: nearestShelterDoc.address,
        district: nearestShelterDoc.district,
        capacity: `${nearestShelterDoc.capacity - nearestShelterDoc.occupied} / ${nearestShelterDoc.capacity} beds free`,
        freeBeds: Math.max(0, nearestShelterDoc.capacity - nearestShelterDoc.occupied),
        totalBeds: nearestShelterDoc.capacity,
        status: nearestShelterDoc.status,
        distance: shelterDistanceStr
      } : null;

      // 5. Authentic hazard assessment and recommended actions tailored to risk tier & hazard
      const probPct = (calibProb * 100).toFixed(1);
      let hazardAssessment = `Normal baseline conditions in ${userDistrict}. Telemetry indicates safe seasonal thresholds (calibrated ${dominantHazardType.toLowerCase()} risk: ${probPct}%).`;
      if (riskLevel === 'MODERATE') {
        hazardAssessment = `Heightened ${dominantHazardType.toLowerCase()} advisory active in ${userDistrict}. Soil moisture and drainage sensors show elevated readings (calibrated risk: ${probPct}%).`;
      } else if (riskLevel === 'HIGH') {
        hazardAssessment = `High ${dominantHazardType.toLowerCase()} hazard detected in ${userDistrict}. Elevated streamflow and heavy precipitation pose potential threat (calibrated risk: ${probPct}%).`;
      } else if (riskLevel === 'CRITICAL') {
        hazardAssessment = `Critical life-safety emergency in ${userDistrict}. Severe runoff or slope instability detected (calibrated risk: ${probPct}%). Evacuation recommended.`;
      }

      let recommendedAction = 'Normal civilian routine permitted. Keep emergency contacts handy.';
      if (riskLevel === 'MODERATE') {
        recommendedAction = 'Keep communication devices charged. Avoid low-lying riverbanks and steep slopes. Monitor official emergency broadcasts.';
      } else if (riskLevel === 'HIGH' || riskLevel === 'CRITICAL') {
        recommendedAction = 'Prepare emergency supplies and proceed to designated relief shelters if instructed by civil defense authorities.';
      }

      return {
        district: userDistrict,
        riskLevel,
        calibratedProbability: calibProb,
        dominantHazard: dominantHazardType,
        safetyScore,
        weatherAlert: alertTitle,
        currentLocation: `${userDistrict}, Karnataka`,
        hazardAssessment,
        recommendedAction,
        nearbyRisksCount,
        nearestShelter,
        activeAdvisoriesCount
      };
    } catch (err) {
      console.error('[DashboardService.getUserDashboardSummary] Error:', err);
      throw err;
    }
  }
}

module.exports = new DashboardService();
