const mongoose = require('mongoose');

const alertSchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: [true, 'Title is required'],
      trim: true
    },
    description: {
      type: String,
      required: [true, 'Description is required'],
      trim: true
    },
    hazardType: {
      type: String,
      enum: ['FLOOD', 'LANDSLIDE', 'HEAVY_RAINFALL', 'GENERAL', 'INFRASTRUCTURE'],
      default: 'GENERAL'
    },
    riskLevel: {
      type: String,
      enum: ['LOW', 'MODERATE', 'HIGH', 'CRITICAL'],
      required: [true, 'Risk level is required']
    },
    district: {
      type: String,
      required: [true, 'District is required'],
      trim: true
    },
    location: {
      type: {
        type: String,
        enum: ['Point'],
        default: 'Point'
      },
      coordinates: {
        type: [Number], // [longitude, latitude]
        default: [0, 0]
      }
    },
    affectedPopulation: {
      type: Number,
      default: 0
    },
    affectedZone: {
      type: String,
      default: 'Mapped riparian hazard sector',
      trim: true
    },
    populationBasis: {
      type: String,
      default: 'Estimated figure, not verified against official DDMP records',
      trim: true
    },
    source: {
      type: String,
      default: 'AegisCore Prediction Engine',
      trim: true
    },
    status: {
      type: String,
      enum: ['ACTIVE', 'RESOLVED', 'CANCELLED'],
      default: 'ACTIVE'
    },
    expiresAt: {
      type: Date,
      default: () => new Date(Date.now() + 24 * 60 * 60 * 1000)
    },
    isAutoGenerated: {
      type: Boolean,
      default: false
    },
    technicalDetails: {
      type: mongoose.Schema.Types.Mixed,
      default: null
    },
    issuedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User'
    }
  },
  {
    timestamps: true
  }
);

alertSchema.index({ location: '2dsphere' });
alertSchema.index({ status: 1, expiresAt: 1 });
alertSchema.index({ district: 1, hazardType: 1, status: 1 });

module.exports = mongoose.model('Alert', alertSchema);
